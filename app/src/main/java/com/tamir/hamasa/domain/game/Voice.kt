    /**
     * Closing line of "סיכום חודש". [kgChange] negative = lost. Only a change toward the goal gets a tail:
     * down for a loss goal, up when [gainGoal] (bulk). A change away adds nothing (never shaming).
     * Three or more records get a tail when the weight did not already get one.
     */
    fun monthClosing(sessions: Int, kgChange: Float?, records: Int, gainGoal: Boolean = false): String {
        val kgUpTails = listOf(
            "והמשקל עלה. בדיוק לפי התוכנית.",
            "והמספר על המשקל טיפס. בכוונה.",
            "והמשקל זז למעלה. המזלג והמוט עבדו יחד."
        )
        val base = when {
            sessions >= 12 -> CharacterNames.g(monthBigLines.random()).format(sessions)
            sessions >= 5 -> CharacterNames.g(monthMidLines.random()).format(sessions)
            sessions >= 2 -> CharacterNames.g(monthLowLines.random()).format(sessions)
            sessions == 1 -> "אימון אחד החודש. הוא נספר. החודש הבא מקבל לו חברים."
            else -> monthZeroLines.random()
        }
        return when {
            gainGoal && kgChange != null && kgChange >= 0.3f -> base + " " + kgUpTails.random()
            !gainGoal && kgChange != null && kgChange <= -0.3f -> base + " " + monthKgDownTails.random()
            records >= 3 -> base + " " + "ו-%d שיאים. הברזל ביקש פגרה.".format(records)
            else -> base
        }
    }
