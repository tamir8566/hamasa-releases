    /** Chapters in one region before the cycle repeats: the region's arc, then the road chapters. */
    fun chaptersPerRegion(region: Int): Int = arcs[region.coerceIn(0, arcs.size - 1)].size + road.size

    private fun chapter(region: Int, step: Int): Ch {
        val arc = arcs[region]
        val k = step % (arc.size + road.size)
        return if (k < arc.size) arc[k] else road[(k - arc.size + region * 2) % road.size]
    }

    /**
     * A chapter of exactly [SENTENCES] lines, in the current hero variant (CharacterNames). [bossName]/[bossQuote]
     * may be blank (no boss this week). [returningLine]: the comeback line of a boss that was beaten before.
     * [step]: how many chapters were already told in this region (the arc is read in order); negative = pick by [seed].
     */
    fun fallback(seed: Long, region: Int, bossName: String, bossQuote: String, returningLine: String? = null, step: Int = -1): List<String> {
        val r = region.coerceIn(0, arcs.size - 1)
        val s = if (seed < 0) -(seed + 1) else seed
        val k = if (step >= 0) step else (s % chaptersPerRegion(r)).toInt()
        val female = CharacterNames.isFemaleNow()
        val ch = chapter(r, k)
        val place = loc[r]
        fun t(x: L): String = x.get(female).replace("{loc}", place)
        val middle: List<String> = when {
            bossName.isBlank() -> listOf(t(ch.mid1), t(ch.mid2))
            else -> {
                val v = ((s + k) % 3).toInt()
                val arrive = if (returningLine != null) t(bossReturn) else t(bossArrive[v])
                val talk = t(bossTalk[v])
                listOf(arrive.format(bossName), talk.format((returningLine ?: bossQuote).trim().trimEnd('.', '!', '?', ',').trim()))
            }
        }
        return listOf(t(ch.open), t(ch.problem)) + middle + listOf(t(ch.act), t(ch.end))
    }

    /** A sample chapter (the river) for the AI prompt, so the model sees the wanted style. */
    fun styleExample(female: Boolean): List<String> {
        val ch = arcs[3][0]
        return listOf(ch.open, ch.problem, ch.mid1, ch.mid2, ch.act, ch.end).map { it.get(female) }
    }

    /** Chapter title: "פרק 12: היער". */
    fun title(chapterNo: Int, regionName: String): String = "פרק ${chapterNo.coerceAtLeast(1)}: $regionName"

    /** How many lines are revealed after [completed] of [planned] sets: the first at the start, the last with the last set. */
    fun revealed(completed: Int, planned: Int, total: Int = SENTENCES): Int {
        if (total <= 0) return 0
        if (planned <= 0) return total
        val c = completed.coerceIn(0, planned)
        return (1 + c * (total - 1) / planned).coerceIn(1, total)
    }

    /**
     * The overused words whose app-wide caps are full (see CLAUDE.md). Spelled in pieces so this list itself
     * does not count as an occurrence.
     */
    val bannedWords: List<String> = listOf("הבינ" + "ותי", "לפרו" + "טוקול", "איננ" + "י")

    /** An AI chapter is accepted only when it is Hebrew only (no Latin letters) and keeps clear of the capped words. */
    fun acceptable(lines: List<String>): Boolean {
        if (lines.size != SENTENCES) return false
        val banned = bannedWords
        for (l in lines) {
            val t = l.trim()
            if (t.isEmpty() || t.length > 160) return false
            if (t.any { it in 'a'..'z' || it in 'A'..'Z' }) return false
            if (banned.any { t.contains(it) }) return false
        }
        return true
    }
