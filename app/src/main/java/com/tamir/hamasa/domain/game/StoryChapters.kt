 *
 * Offline chapters: a simple, continuous adventure in plain Hebrew. Every chapter is ONE small clear event
 * (where, what went wrong, what the hero did, how it ended) told in [SENTENCES] short lines.
 * Each region of the map has an ordered mini-arc of [Ch] chapters that follow each other (chapter 2 refers to
 * chapter 1, the last one leads to the next region), then a few road chapters that fit any region ({loc}).
 * The caller passes the chapter's place in the region ([step], = chapters already told in this region);
 * without it the session id picks one (deterministic: the same workout always tells the same chapter).
 *
 * The boss of the week walks into the event as a character: lines 3-4 of the chapter are then replaced by the
 * boss meeting (name + quote). Lines 5-6 of every chapter therefore depend only on lines 1-2.
 *
 * Every line is written twice: for שמביולוק and for שמביולוקה (hero variant at build time, CharacterNames).
 * Pure, no Android types.
 */
