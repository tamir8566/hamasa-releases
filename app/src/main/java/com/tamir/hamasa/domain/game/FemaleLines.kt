 * Female grammar for the hero's lines (Prefs.characterVariant "F" = שמביולוקה). Used only through
 * [CharacterNames.g]: exact male line (as written in the catalogs, placeholders like %s / %d / %.1f / %02d
 * included) -> the same line in female grammar. Only lines whose grammar is gendered are here; the rest
 * stay as they are (the name, if present, is swapped by [CharacterNames.femaleName]).
 * Placeholders in a value must be exactly the ones of its key (String.format runs after the lookup).
 *
 * Word caps of CLAUDE.md: a few male lines contain capped words. Their keys spell the capped word as a
 * token ({A}, {H}, {L}), so this file does not add occurrences; [forLine] turns the real words into the
