        ("איננ" + "י") to "{A}",
        ("הבינ" + "ותי") to "{H}",
        ("לפרו" + "טוקול") to "{L}"
    )

    private fun key(line: String): String {
        var k = line
        for ((word, token) in capped) if (k.contains(word)) k = k.replace(word, token)
        return k
    }

    /** The female version of [line], or null when the line has no override. */
    fun forLine(line: String): String? {
        val k = key(line)
        return lines[k] ?: FemaleLinesA.lines[k] ?: FemaleLinesB.lines[k] ?: FemaleLinesC.lines[k] ?: FemaleLinesD.lines[k]
    }

